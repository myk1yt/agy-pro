/**
 * Normalizes any locale string (env var, system locale, CLI arg) to a supported code.
 * Handles language codes, region subtags, and script subtags cleanly.
 * @param {string} raw - Raw locale string (e.g. 'zh-TW', 'zh_TW.UTF-8', 'zh-Hant-TW', 'de-DE', 'en').
 * @returns {string|null} Resolved supported locale code or null.
 */
function normalizeLocale(raw) {
  if (!raw || typeof raw !== 'string') return null;
  const cleaned = raw.split('.')[0].replace(/_/g, '-').trim();

  // 1. Exact match (e.g. 'zh-TW', 'en', 'ko')
  if (SUPPORTED_LOCALES.includes(cleaned)) return cleaned;

  // 2. Case-insensitive exact match (e.g. 'zh-tw' -> 'zh-TW')
  const exact = SUPPORTED_LOCALES.find(l => l.toLowerCase() === cleaned.toLowerCase());
  if (exact) return exact;

  // 3. Traditional Chinese dialect / script match (e.g. 'zh-Hant', 'zh-HK', 'zh-MO')
  const lower = cleaned.toLowerCase();
  if (lower.startsWith('zh') && (lower.includes('tw') || lower.includes('hant') || lower.includes('hk') || lower.includes('mo'))) {
    if (SUPPORTED_LOCALES.includes('zh-TW')) return 'zh-TW';
  }

  // 4. Base language prefix match (e.g. 'en-US' -> 'en', 'de-AT' -> 'de', 'pt-BR' -> 'pt')
  const base = lower.split('-')[0];
  const baseMatch = SUPPORTED_LOCALES.find(l => l.toLowerCase() === base);
  if (baseMatch) return baseMatch;

  return null;
}

/**
 * Checks whether a locale uses Right-to-Left (RTL) writing direction.
 * @param {string} [locale] - Locale code. Defaults to current active locale.
 * @returns {boolean} True if RTL.
 */
function isRtl(locale = null) {
  const loc = normalizeLocale(locale || currentLocale) || DEFAULT_LOCALE;
  const base = loc.toLowerCase().split('-')[0];
  return RTL_LOCALES.includes(base);
}

/**
 * Automatically detects the user's system locale.
 * Priority: AGY_LANG -> Intl.DateTimeFormat -> LC_ALL -> LANG -> LANGUAGE -> fallback
 * @returns {string} One of supported locale codes.
 */
function detectSystemLocale() {
  if (process.env.AGY_LANG) {
    const norm = normalizeLocale(process.env.AGY_LANG);
    if (norm) return norm;
  }

  try {
    const intlLocale = Intl.DateTimeFormat().resolvedOptions().locale;
    if (intlLocale) {
      const norm = normalizeLocale(intlLocale);
      if (norm) return norm;
    }
  } catch (_err) {
    // Fallback if Intl API fails
  }

  const envLang =
    process.env.LC_ALL ||
    process.env.LANG ||
    process.env.LANGUAGE;

  if (envLang) {
    const norm = normalizeLocale(envLang);
    if (norm) return norm;
  }

  return DEFAULT_LOCALE;
}

/**
 * Current active locale in state.
 */
let currentLocale = detectSystemLocale();

/**
 * Sets the active locale.
 * @param {string} locale - Target locale code.
 * @returns {string} The resolved active locale.
 */
function setLocale(locale) {
  if (!locale) return currentLocale;
  const normalized = normalizeLocale(locale);
  if (normalized) {
    currentLocale = normalized;
  } else {
    currentLocale = DEFAULT_LOCALE;
  }
  return currentLocale;
}

/**
 * Gets the current active locale.
 * @returns {string}
 */
function getLocale() {
  return currentLocale;
}

/**
 * Translates a key with optional parameter substitution.
 * @param {string} key - Translation key.
 * @param {object} [params] - Key-value map for string interpolation {var}.
 * @param {string} [overrideLocale] - Specific locale override.
 * @returns {string} Translated string.
 */
function t(key, params = {}, overrideLocale = null) {
  const loc = overrideLocale ? (normalizeLocale(overrideLocale) || DEFAULT_LOCALE) : currentLocale;
  const dict = TRANSLATIONS[loc] || TRANSLATIONS[DEFAULT_LOCALE];
  let template = dict[key] || TRANSLATIONS[DEFAULT_LOCALE][key] || key;

  if (params && typeof params === 'object') {
    for (const [k, val] of Object.entries(params)) {
      template = template.replace(new RegExp(`\\{${k}\\}`, 'g'), String(val));
    }
  }

  return template;
}

/**
 * Gets all translations for a given locale (or the active locale), overlaid on default locale.
 * @param {string} [locale] - Target locale code.
 * @returns {object} Full translation dictionary.
 */
function getAllTranslations(locale = null) {
  const loc = locale ? (normalizeLocale(locale) || DEFAULT_LOCALE) : currentLocale;
  const dict = TRANSLATIONS[loc] || TRANSLATIONS[DEFAULT_LOCALE];
  const all = Object.assign({}, TRANSLATIONS[DEFAULT_LOCALE], dict);
  if (!all.colCache && all.colCached) {
    all.colCache = all.colCached;
  }
  return all;
}

