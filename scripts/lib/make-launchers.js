#!/usr/bin/env node

/**
 * @fileoverview Generates the self-healing Windows launchers (.bat shims), their
 * companion root resolver (agy-root-resolve.js), and the root marker used by
 * them, for the agy-tools installer.
 *
 * Rationale: the previous fallback launchers froze the install-time absolute
 * repository path (ROOT_DIR) into every generated .bat file, so moving or
 * renaming the clone silently broke the statusLine hook and the PostInvocation
 * hook. The launchers generated here contain no absolute path at all: they hand
 * the work to the companion resolver written next to them, which reads a root
 * marker at run time, validates it, falls back to a bounded rescan of the user
 * profile, and repairs the marker.
 *
 * Why a Node resolver instead of a pure-cmd rescan: cmd offers no depth-bounded
 * directory walk (`dir /s` has no depth switch) and no way to prune reparse
 * points during traversal. Measured on this machine (scratch/_w1a/probe1.bat):
 * `dir /s /b /a-d` descends INTO a junction and lists files on the far side of
 * it, and `/ad-l` only filters the listing — the traversal still enters the
 * junction (`.../home/zz_link/bin` is listed). Node's readdir + lstat reports
 * the junction as a link, so the walk skips it, and the depth bound is ours to
 * enforce.
 *
 * Adoption rule: a scan candidate is adopted only when it is a root of THIS
 * product — package.json parses, its "name" equals PACKAGE_NAME, and every wired
 * entry script exists under bin/. Two or more candidates is an ambiguity error:
 * nothing is adopted and the marker is left untouched. The marker's own
 * recorded path stays the first preference.
 *
 * Delayed expansion is deliberately disabled in the generated shims so that '!'
 * in a path or argument survives verbatim.
 *
 * The marker is the only artifact that holds an absolute path, and it is
 * rewritten atomically (temp file + rename) by the resolver whenever it goes
 * stale.
 */

'use strict';

const crypto = require('crypto');
const fs = require('fs');
const os = require('os');
const path = require('path');

const MARKER_TAIL = ['.gemini', 'antigravity-cli', 'agy-root.txt'];
const PACKAGE_NAME = 'agy-tools';
const SCAN_MAX_DEPTH = 6;
const RESOLVER_FILE = 'agy-root-resolve.js';

const SHIM_ENTRIES = [
  { name: 'agy-tools.bat', script: 'agy-tools.js' },
  { name: 'antigravity-tools.bat', script: 'agy-tools.js' },
  { name: 'agy-tokens.bat', script: 'agy-tokens.js' },
  { name: 'agy-dashboard.bat', script: 'agy-dashboard.js' }
];

/** Every distinct bin script the shim table wires (the identity check covers all of them). */
const ENTRY_SCRIPTS = Array.from(new Set(SHIM_ENTRIES.map((entry) => entry.script)));

const SHIM_TEMPLATE = `@echo off
rem ---------------------------------------------------------------------------
rem Generated by scripts/lib/make-launchers.js (agy-tools installer).
rem Self-healing launcher: no absolute path is stored in this file. The toolkit
rem root is re-resolved on every run by the companion resolver ${RESOLVER_FILE}
rem written next to this launcher, which validates the root marker, rescans the
rem configured scan root on a depth-__DEPTH__ walk that skips reparse points,
rem junctions and symlinks, and repairs the marker.
rem Delayed expansion stays disabled on purpose: '!' in a path or an argument
rem must survive verbatim.
rem Do not edit by hand: re-run scripts\\install.bat instead.
rem ---------------------------------------------------------------------------
setlocal disabledelayedexpansion
set "AGY_ROOT_MARKER=__MARKER__"
set "AGY_MARKER_DIR=__MARKER_DIR__"
set "AGY_RESOLVER=__RESOLVER__"
set "AGY_SCAN_HOME=__SCAN_HOME__"
set "AGY_SCRIPT=__SCRIPT__"
set "AGY_ROOT="
if exist "%AGY_RESOLVER%" goto agy_resolve_root
>&2 echo [agy-tools] ERROR: root resolver missing: %AGY_RESOLVER%
>&2 echo [agy-tools] Fix: re-run the installer from the toolkit repository:
>&2 echo [agy-tools]      scripts\\install.bat   [Windows]
exit /b 1

:agy_resolve_root
for /f "usebackq delims=" %%R in (\`node "%AGY_RESOLVER%" --marker "%AGY_ROOT_MARKER%" --home "%AGY_SCAN_HOME%" --script "%AGY_SCRIPT%"\`) do set "AGY_ROOT=%%R"
if not defined AGY_ROOT exit /b 1
if not exist "%AGY_ROOT%\\bin\\%AGY_SCRIPT%" exit /b 1
node "%AGY_ROOT%\\bin\\%AGY_SCRIPT%" %*
exit /b %ERRORLEVEL%
`;

const RESOLVER_TEMPLATE = `#!/usr/bin/env node

/**
 * @fileoverview Companion root resolver for the generated agy-tools .bat
 * launchers. Generated by scripts/lib/make-launchers.js — do not edit by hand.
 *
 * Resolution order:
 *   1. The path recorded in the root marker, when it still passes the full
 *      identity check (package.json parses, name is the product name, every
 *      wired entry script exists under bin/).
 *   2. A depth-bounded rescan of the scan root that never enters a reparse
 *      point, junction, or symlink and never considers a UNC path or a path
 *      outside the scan root.
 *        - exactly one identity-passing candidate: adopt it, rewrite the marker
 *          atomically (temp file + rename), print it on stdout;
 *        - two or more: print every candidate on stderr, adopt nothing, leave
 *          the marker untouched, exit AMBIGUOUS;
 *        - none: exit NOT_FOUND with the reinstall hint.
 *
 * stdout carries the resolved root and nothing else (the launcher reads it with
 * for /f); every diagnostic goes to stderr so it reaches the user's console.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const PRODUCT = '__PRODUCT__';
const PKG_NAME = '__PKG_NAME__';
const ENTRY_SCRIPTS = __ENTRY_SCRIPTS__;
const DEFAULT_DEPTH = __MAX_DEPTH__;
const BS = String.fromCharCode(92);
const CRLF = String.fromCharCode(13, 10);
const EXIT_OK = 0;
const EXIT_USAGE = 2;
const EXIT_NOT_FOUND = 3;
const EXIT_AMBIGUOUS = 4;
const EXIT_MARKER_WRITE = 5;

function logLine(message) {
  process.stderr.write('[agy-tools] ' + message + CRLF);
}

function parseFlags(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (token.slice(0, 2) !== '--') continue;
    const key = token.slice(2);
    const next = argv[i + 1];
    if (next === undefined || next.slice(0, 2) === '--') {
      flags[key] = true;
    } else {
      flags[key] = next;
      i += 1;
    }
  }
  return flags;
}

function isUncPath(candidate) {
  const prefix = candidate.slice(0, 2);
  return prefix === BS + BS || prefix === '//';
}

function isInsideRoot(root, candidate) {
  const rel = path.relative(root, candidate);
  if (rel === '') return true;
  return rel.slice(0, 2) !== '..' && !path.isAbsolute(rel);
}

function hasScript(root, script) {
  if (!script) return true;
  try {
    return fs.statSync(path.join(root, 'bin', script)).isFile();
  } catch (err) {
    return false;
  }
}

function identityOk(root) {
  if (!root || isUncPath(root)) return false;
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  } catch (err) {
    return false;
  }
  if (!pkg || typeof pkg !== 'object' || pkg.name !== PKG_NAME) return false;
  for (let i = 0; i < ENTRY_SCRIPTS.length; i += 1) {
    if (!hasScript(root, ENTRY_SCRIPTS[i])) return false;
  }
  return true;
}

function scanCandidates(base, depth) {
  const found = [];
  let level = [base];
  for (let current = 0; current <= depth && level.length > 0; current += 1) {
    const next = [];
    for (let i = 0; i < level.length; i += 1) {
      const dir = level[i];
      if (identityOk(dir)) found.push(dir);
      if (current === depth) continue;
      let entries;
      try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
      } catch (err) {
        continue;
      }
      for (let e = 0; e < entries.length; e += 1) {
        const entry = entries[e];
        if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
        const child = path.join(dir, entry.name);
        let stat;
        try {
          stat = fs.lstatSync(child);
        } catch (err) {
          continue;
        }
        if (stat.isSymbolicLink()) continue;
        if (!stat.isDirectory()) continue;
        next.push(child);
      }
    }
    level = next;
  }
  return found;
}

function writeMarkerAtomic(markerPath, root) {
  const dir = path.dirname(markerPath);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = path.join(dir, '.agy-root.' + process.pid + '.' + Date.now() + '.tmp');
  fs.writeFileSync(tmp, path.resolve(root) + CRLF, 'utf8');
  fs.renameSync(tmp, markerPath);
}

function readMarker(markerPath) {
  try {
    const raw = String(fs.readFileSync(markerPath, 'utf8'));
    return raw.split(CRLF).join(String.fromCharCode(10)).split(String.fromCharCode(10))[0].trim();
  } catch (err) {
    return '';
  }
}

function emit(root) {
  process.stdout.write(root + CRLF);
  return EXIT_OK;
}

function main(argv) {
  const flags = parseFlags(argv);
  const markerPath = typeof flags.marker === 'string' ? flags.marker : '';
  const home = typeof flags.home === 'string' ? flags.home : '';
  const script = typeof flags.script === 'string' ? flags.script : ENTRY_SCRIPTS[0];
  const requestedDepth = Number(flags.depth);
  const depth = Number.isInteger(requestedDepth) && requestedDepth >= 0 ? requestedDepth : DEFAULT_DEPTH;

  if (!markerPath) {
    logLine('ERROR: --marker <path> is required');
    return EXIT_USAGE;
  }

  // 1. The marker's own recorded path is the first preference.
  const recorded = readMarker(markerPath);
  if (recorded && identityOk(recorded) && hasScript(recorded, script)) {
    return emit(path.resolve(recorded));
  }

  // 2. Bounded, reparse-point-safe rescan of the scan root.
  if (!home) {
    logLine('ERROR: --home <directory> is required when the root marker is stale');
    return EXIT_USAGE;
  }
  const base = path.resolve(home);
  let candidates = [];
  try {
    if (fs.statSync(base).isDirectory()) candidates = scanCandidates(base, depth);
  } catch (err) {
    candidates = [];
  }
  candidates = candidates
    .filter(function keep(candidate) { return hasScript(candidate, script) && isInsideRoot(base, candidate); })
    .map(function normalize(candidate) { return path.resolve(candidate); })
    .filter(function unique(candidate, index, all) { return all.indexOf(candidate) === index; });

  if (candidates.length === 1) {
    const root = candidates[0];
    try {
      writeMarkerAtomic(markerPath, root);
    } catch (err) {
      logLine('ERROR: found the root but could not write the root marker: ' + markerPath);
      logLine('  reason: ' + err.message);
      logLine('Fix: check the permissions of the marker directory, then re-run the installer:');
      logLine('     scripts' + BS + 'install.bat   (Windows)');
      return EXIT_MARKER_WRITE;
    }
    logLine('repaired root marker, root is now: ' + root);
    return emit(root);
  }

  if (candidates.length > 1) {
    logLine('ERROR: ' + candidates.length + ' candidate ' + PRODUCT + ' roots found; refusing to adopt any of them.');
    for (let i = 0; i < candidates.length; i += 1) logLine('  candidate: ' + candidates[i]);
    logLine('ERROR: root marker left untouched: ' + markerPath);
    logLine('Fix: remove or rename the stale copies above, or re-run the installer from the clone you want:');
    logLine('     scripts' + BS + 'install.bat   (Windows)');
    return EXIT_AMBIGUOUS;
  }

  logLine('ERROR: the ' + PRODUCT + ' repository root could not be found.');
  logLine('  marker : ' + markerPath);
  logLine('  scanned: ' + base + ' for bin/' + script + ' (depth ' + depth + ', reparse points skipped)');
  logLine('Fix: re-run the installer from the toolkit repository:');
  logLine('     scripts' + BS + 'install.bat   (Windows)');
  return EXIT_NOT_FOUND;
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    logLine('ERROR: ' + (err && err.message ? err.message : String(err)));
    process.exitCode = EXIT_USAGE;
  }
}

module.exports = {
  DEFAULT_DEPTH: DEFAULT_DEPTH,
  ENTRY_SCRIPTS: ENTRY_SCRIPTS,
  identityOk: identityOk,
  main: main,
  scanCandidates: scanCandidates
};
`;

/**
 * Resolve the home directory the installer runs as.
 * @param {Object} [env] - Environment object.
 * @returns {string} Absolute home directory.
 */
function getHomeDir(env = process.env) {
  return env.USERPROFILE || env.HOME || os.homedir();
}

/**
 * Default marker location: <home>/.gemini/antigravity-cli/agy-root.txt
 * @param {string} [home]
 * @returns {string} Absolute marker path.
 */
function defaultMarkerPath(home = getHomeDir()) {
  return path.join(home, ...MARKER_TAIL);
}

/**
 * Default directory for the generated shims and the companion resolver:
 * <home>/.gemini/antigravity-cli/bin
 * @param {string} [home]
 * @returns {string} Absolute directory.
 */
function defaultBinDir(home = getHomeDir()) {
  return path.join(path.dirname(defaultMarkerPath(home)), 'bin');
}

/**
 * Parse one package.json and require the product name plus every wired entry
 * script, so a candidate is adopted only when it is a root of THIS product.
 * @param {string} dir - Candidate root.
 * @returns {boolean} True when the directory is an identity-passing root.
 */
function isRepoRoot(dir) {
  if (!dir) return false;
  const resolved = path.resolve(dir);
  const prefix = resolved.slice(0, 2);
  if (prefix === '\\\\' || prefix === '//') return false;
  let pkg;
  try {
    pkg = JSON.parse(fs.readFileSync(path.join(resolved, 'package.json'), 'utf8'));
  } catch (_err) {
    return false;
  }
  if (!pkg || typeof pkg !== 'object' || pkg.name !== PACKAGE_NAME) return false;
  return ENTRY_SCRIPTS.every((script) => {
    try {
      return fs.statSync(path.join(resolved, 'bin', script)).isFile();
    } catch (_err) {
      return false;
    }
  });
}

/**
 * Express an absolute path as a cmd expansion rooted at %USERPROFILE%. The
 * profile variable is emitted ONLY when the install home really is the
 * USERPROFILE path; otherwise the absolute path is emitted, because %USERPROFILE%
 * would then expand to a different directory (USERPROFILE||HOME||homedir).
 * @param {string} target - Absolute path.
 * @param {string} home - Home directory the installer resolved.
 * @param {string} [profile] - USERPROFILE value (default: process.env.USERPROFILE).
 * @returns {string} cmd expression that expands to the path at run time.
 */
function relativizeToHome(target, home, profile = process.env.USERPROFILE) {
  const resolvedTarget = path.resolve(target);
  const resolvedHome = path.resolve(home);
  const resolvedProfile = profile ? path.resolve(String(profile).trim()) : '';
  const homeIsProfile =
    resolvedProfile !== '' &&
    resolvedProfile.toLowerCase() === resolvedHome.toLowerCase();
  if (!homeIsProfile) return resolvedTarget;
  const rel = path.relative(resolvedHome, resolvedTarget);
  return rel === '' ? '%USERPROFILE%' : `%USERPROFILE%\\${rel}`;
}

/**
 * Render the companion resolver source (agy-root-resolve.js).
 * @returns {string} Resolver source, LF-joined.
 */
function renderRootResolver() {
  return RESOLVER_TEMPLATE
    .split('__PRODUCT__').join(PACKAGE_NAME)
    .split('__PKG_NAME__').join(PACKAGE_NAME)
    .split('__ENTRY_SCRIPTS__').join(JSON.stringify(ENTRY_SCRIPTS))
    .split('__MAX_DEPTH__').join(String(SCAN_MAX_DEPTH));
}

/**
 * Render the body of one .bat launcher.
 * @param {Object} opts - Render options.
 * @param {string} opts.script - Target bin script name (e.g. agy-tokens.js).
 * @param {string} opts.markerPath - Absolute marker path.
 * @param {string} [opts.home] - Home directory used for relativization.
 * @param {string} [opts.resolverPath] - Absolute resolver path (default: <home>/.../bin/<RESOLVER_FILE>).
 * @param {string} [opts.profile] - USERPROFILE value used for relativization.
 * @returns {string} CRLF-joined shim content.
 */
function renderShim(opts) {
  const home = opts.home || getHomeDir();
  const markerPath = opts.markerPath || defaultMarkerPath(home);
  const resolverPath = opts.resolverPath || path.join(defaultBinDir(home), RESOLVER_FILE);
  const markerExpr = relativizeToHome(markerPath, home, opts.profile);
  const markerDirExpr = relativizeToHome(path.dirname(markerPath), home, opts.profile);
  const resolverExpr = relativizeToHome(resolverPath, home, opts.profile);
  const homeExpr = relativizeToHome(home, home, opts.profile);

  return SHIM_TEMPLATE
    .split('__DEPTH__').join(String(SCAN_MAX_DEPTH))
    .split('__MARKER_DIR__').join(markerDirExpr)
    .split('__MARKER__').join(markerExpr)
    .split('__RESOLVER__').join(resolverExpr)
    .split('__SCAN_HOME__').join(homeExpr)
    .split('__SCRIPT__').join(opts.script)
    .replace(/\r\n/g, '\n')
    .replace(/\n/g, '\r\n');
}

/**
 * Write the root marker file atomically (temp file in the same directory +
 * rename), so a concurrent statusline render never reads a torn marker.
 * @param {Object} opts
 * @param {string} opts.root - Repository root to record.
 * @param {string} [opts.markerPath] - Absolute marker path.
 * @returns {string} Marker path written.
 */
function writeMarker(opts) {
  const markerPath = opts.markerPath || defaultMarkerPath();
  fs.mkdirSync(path.dirname(markerPath), { recursive: true });
  const tmp = path.join(
    path.dirname(markerPath),
    `.agy-root.${crypto.randomBytes(6).toString('hex')}.tmp`
  );
  fs.writeFileSync(tmp, `${path.resolve(opts.root)}\r\n`, 'utf8');
  fs.renameSync(tmp, markerPath);
  return markerPath;
}

/**
 * Write the root marker, the companion resolver, and the fallback launchers.
 * The marker is written FIRST: a launcher that exists while the marker does not
 * would self-heal on every single run.
 * @param {Object} opts
 * @param {string} opts.binDir - Directory that receives the .bat shims.
 * @param {string} opts.root - Repository root the marker records.
 * @param {string[]} [opts.names] - Shim file names to generate.
 * @param {string} [opts.markerPath] - Absolute marker path.
 * @param {string} [opts.home] - Home directory used for relativization.
 * @param {string} [opts.profile] - USERPROFILE value used for relativization.
 * @returns {{marker: string, resolver: string, written: string[]}} Result summary.
 */
function writeLaunchers(opts) {
  const home = opts.home || getHomeDir();
  const markerPath = opts.markerPath || defaultMarkerPath(home);
  const root = path.resolve(opts.root);

  if (!isRepoRoot(root)) {
    throw new Error(
      `not an agy-tools repository root (package.json "name" must be ${PACKAGE_NAME} and bin/ must hold ${ENTRY_SCRIPTS.join(', ')}): ${root}`
    );
  }

  const requested = opts.names && opts.names.length
    ? opts.names.map((name) => name.trim()).filter(Boolean)
    : SHIM_ENTRIES.map((entry) => entry.name);

  const byName = new Map(SHIM_ENTRIES.map((entry) => [entry.name, entry]));
  const planned = requested.map((name) => {
    const entry = byName.get(name);
    if (!entry) throw new Error(`unknown launcher name: ${name}`);
    return entry;
  });

  const marker = writeMarker({ root, markerPath });

  fs.mkdirSync(opts.binDir, { recursive: true });

  const resolver = path.join(opts.binDir, RESOLVER_FILE);
  fs.writeFileSync(resolver, renderRootResolver(), 'utf8');

  const written = [];
  for (const entry of planned) {
    const target = path.join(opts.binDir, entry.name);
    fs.writeFileSync(
      target,
      renderShim({ script: entry.script, markerPath, home, resolverPath: resolver, profile: opts.profile }),
      'utf8'
    );
    written.push(target);
  }

  return { marker, resolver, written };
}

/**
 * Parse `--flag value` pairs out of argv.
 * @param {string[]} argv - Raw arguments.
 * @returns {Object} Flag map.
 */
function parseFlags(argv) {
  const flags = {};
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i];
    if (!token.startsWith('--')) continue;
    const key = token.slice(2);
    const next = argv[i + 1];
    if (next === undefined || next.startsWith('--')) {
      flags[key] = true;
    } else {
      flags[key] = next;
      i += 1;
    }
  }
  return flags;
}

function main(argv) {
  const command = argv[0];
  const flags = parseFlags(argv.slice(1));
  const home = flags.home ? String(flags.home) : getHomeDir();
  const markerPath = flags.marker ? String(flags.marker) : defaultMarkerPath(home);
  const root = flags.root ? String(flags.root) : path.resolve(__dirname, '..', '..');

  if (command === 'bat') {
    if (!flags.bin) throw new Error('missing --bin <directory>');
    const names = typeof flags.names === 'string' ? flags.names.split(',') : undefined;
    const result = writeLaunchers({
      binDir: String(flags.bin),
      root,
      names,
      markerPath,
      home
    });
    process.stdout.write(`[INFO] wrote root marker: ${result.marker}\r\n`);
    process.stdout.write(`[INFO] wrote root resolver: ${result.resolver}\r\n`);
    for (const file of result.written) {
      process.stdout.write(`[INFO] wrote launcher: ${file}\r\n`);
    }
    return 0;
  }

  if (command === 'marker') {
    if (!isRepoRoot(root)) {
      throw new Error(`not an agy-tools repository root: ${root}`);
    }
    const written = writeMarker({ root, markerPath });
    process.stdout.write(`[INFO] wrote root marker: ${written}\r\n`);
    return 0;
  }

  if (command === 'verify') {
    const candidate = flags.root ? String(flags.root) : '';
    const ok = isRepoRoot(candidate);
    process.stdout.write(`${ok ? 'ok' : 'missing'}: ${candidate}\r\n`);
    return ok ? 0 : 1;
  }

  throw new Error(`unknown command: ${command || '(none)'} (expected bat | marker | verify)`);
}

if (require.main === module) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`[ERROR] ${error.message}\r\n`);
    process.exitCode = 1;
  }
}

