#!/usr/bin/env bash
set -e

echo "======================================================="
echo "  Antigravity CLI Developer Toolkit (agy-tools) Installer"
echo "======================================================="

if ! command -v node >/dev/null 2>&1; then
    echo "[ERROR] Node.js is not installed or not in your PATH."
    echo "Please install Node.js (v16+) from https://nodejs.org/"
    exit 1
fi

if ! node -e "process.exit(parseInt(process.versions.node.split('.')[0], 10) >= 16 ? 0 : 1)" >/dev/null 2>&1; then
    echo "[ERROR] Node.js version 16 or higher is required."
    echo "Current version: $(node -v 2>/dev/null || echo 'unknown')"
    echo "Please upgrade Node.js from https://nodejs.org/"
    exit 1
fi

if ! command -v npm >/dev/null 2>&1; then
    echo "[ERROR] npm is not installed or not in your PATH."
    echo "Please ensure npm is installed and in your PATH."
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

ROOT_MARKER="$HOME/.local/share/agy-tools-root"

chmod +x "$ROOT_DIR/bin/agy-tools.js" 2>/dev/null || true
chmod +x "$ROOT_DIR/bin/agy-tokens.js" 2>/dev/null || true
chmod +x "$ROOT_DIR/bin/agy-dashboard.js" 2>/dev/null || true

# Records the repository root for the self-healing wrappers. The wrappers read this
# file at run time and repair it themselves when the repository moves.
# The write is atomic (private mktemp file + rename) so a concurrent statusline
# render never reads a torn marker, and it is FATAL: a marker that cannot be
# written would leave every wrapper rescanning on every single run.
write_root_marker() {
    _marker_dir="$(dirname "$ROOT_MARKER")"
    if ! mkdir -p "$_marker_dir" 2>/dev/null; then
        echo "[ERROR] Could not create the marker directory: $_marker_dir" >&2
        return 1
    fi
    _marker_tmp="$(mktemp "$_marker_dir/.agy-root.XXXXXX" 2>/dev/null)" || {
        echo "[ERROR] Could not create a marker temp file in: $_marker_dir" >&2
        return 1
    }
    if ! printf '%s\n' "$1" > "$_marker_tmp"; then
        rm -f "$_marker_tmp"
        echo "[ERROR] Could not write the marker temp file: $_marker_tmp" >&2
        return 1
    fi
    if ! mv -f "$_marker_tmp" "$ROOT_MARKER"; then
        rm -f "$_marker_tmp"
        echo "[ERROR] Could not install the root marker: $ROOT_MARKER" >&2
        return 1
    fi
    return 0
}

# Writes one self-healing wrapper. The body carries no absolute path: it reads the
# marker, verifies it, rescans $HOME when the marker is stale, and fails loudly
# (nonzero exit plus the reinstall hint) when the repository cannot be found.
# The rescan is depth-bounded and POSIX-only: it uses a shell queue rather than
# the GNU-only depth switch of find, never enters a symlink, and never guesses
# between two identity-passing candidates.
write_wrapper() {
    _dest="$1"
    _script="$2"
    sed "s/__AGY_SCRIPT__/$_script/g" > "$_dest" <<'AGY_TOOLS_WRAPPER'
#!/bin/sh
# Generated by scripts/install.sh (agy-tools installer).
# Self-healing wrapper: no absolute path is stored in this file. The toolkit
# repository root is re-resolved on every run from the marker below, so the
# wrapper keeps working after the repository is moved or renamed.
# The rescan is depth-bounded (AGY_TOOLS_SCAN_DEPTH), never enters a symlink,
# and never adopts a path that is not a root of this product: package.json must
# parse and name it, and every wired entry script must exist. Two or more
# candidates is a loud failure, and the marker is left untouched.
# Do not edit by hand: re-run scripts/install.sh instead.
AGY_TOOLS_MARKER="${HOME}/.local/share/agy-tools-root"
AGY_TOOLS_SCRIPT="__AGY_SCRIPT__"
AGY_TOOLS_PKG_NAME="agy-tools"
AGY_TOOLS_SCAN_DEPTH=6
AGY_TOOLS_ENTRY_SCRIPTS="agy-tools.js agy-tokens.js agy-dashboard.js"

agy_tools_fail() {
    printf '%s\n' "[agy-tools] ERROR: $1" >&2
}

agy_tools_reinstall_hint() {
    printf '%s\n' "[agy-tools] Fix: re-run the installer from the toolkit repository:" >&2
    printf '%s\n' "[agy-tools]      bash scripts/install.sh" >&2
}

# Identity check: package.json parses AND names this product, and every wired
# entry script exists under bin/. UNC paths are refused outright.
agy_tools_identity_ok() {
    agy_root="$1"
    [ -n "$agy_root" ] || return 1
    [ -d "$agy_root" ] || return 1
    case "$agy_root" in
        //*) return 1 ;;
        \\*) return 1 ;;
    esac
    [ -f "$agy_root/package.json" ] || return 1
    for agy_entry in $AGY_TOOLS_ENTRY_SCRIPTS; do
        [ -f "$agy_root/bin/$agy_entry" ] || return 1
    done
    node -e "try{process.exit(JSON.parse(require('fs').readFileSync(process.argv[1],'utf8')).name==='agy-tools'?0:1)}catch(e){process.exit(1)}" "$agy_root/package.json" 2>/dev/null
}

# Depth-bounded walk of the scan root. Prints every identity-passing candidate
# root, one per line. Symlinks are never entered (the tree outside a symlink is
# not part of the install), and no GNU-only depth switch is used, so the same
# code runs on GNU, BSD and macOS userlands. Verified on this host under bash;
# macOS itself was not available for a live run.
agy_tools_scan() {
    agy_base="$1"
    agy_level="$(mktemp "${TMPDIR:-/tmp}/agy-tools-level.XXXXXX")" || return 1
    agy_next="$(mktemp "${TMPDIR:-/tmp}/agy-tools-next.XXXXXX")" || {
        rm -f "$agy_level"
        return 1
    }
    printf '%s\n' "$agy_base" > "$agy_level"
    agy_depth=0
    while [ "$agy_depth" -le "$AGY_TOOLS_SCAN_DEPTH" ]; do
        : > "$agy_next"
        while IFS= read -r agy_dir; do
            [ -n "$agy_dir" ] || continue
            if agy_tools_identity_ok "$agy_dir"; then
                printf '%s\n' "$agy_dir"
            fi
            [ "$agy_depth" -lt "$AGY_TOOLS_SCAN_DEPTH" ] || continue
            for agy_child in "$agy_dir"/*; do
                [ -d "$agy_child" ] || continue
                [ -L "$agy_child" ] && continue
                printf '%s\n' "$agy_child" >> "$agy_next"
            done
        done < "$agy_level"
        cat "$agy_next" > "$agy_level"
        agy_depth=$((agy_depth + 1))
    done
    rm -f "$agy_level" "$agy_next"
}

# Atomic marker write: private mktemp file in the target directory + rename.
agy_tools_write_marker() {
    agy_marker_dir="$(dirname "$AGY_TOOLS_MARKER")"
    mkdir -p "$agy_marker_dir" 2>/dev/null || return 1
    agy_marker_tmp="$(mktemp "$agy_marker_dir/.agy-root.XXXXXX" 2>/dev/null)" || return 1
    if ! printf '%s\n' "$1" > "$agy_marker_tmp"; then
        rm -f "$agy_marker_tmp"
        return 1
    fi
    if ! mv -f "$agy_marker_tmp" "$AGY_TOOLS_MARKER" 2>/dev/null; then
        rm -f "$agy_marker_tmp"
        return 1
    fi
    return 0
}

AGY_TOOLS_ROOT=""
if [ -f "$AGY_TOOLS_MARKER" ]; then
    AGY_TOOLS_ROOT="$(head -n 1 "$AGY_TOOLS_MARKER" 2>/dev/null | tr -d '\r')"
fi

if ! agy_tools_identity_ok "$AGY_TOOLS_ROOT"; then
    printf '%s\n' "[agy-tools] WARN: root marker missing or stale, rescanning $HOME (depth $AGY_TOOLS_SCAN_DEPTH, symlinks skipped) ..." >&2
    AGY_TOOLS_MATCHES="$(mktemp "${TMPDIR:-/tmp}/agy-tools-matches.XXXXXX")" || exit 1
    agy_tools_scan "$HOME" > "$AGY_TOOLS_MATCHES"
    AGY_TOOLS_COUNT="$(grep -c . "$AGY_TOOLS_MATCHES" 2>/dev/null)"
    [ -n "$AGY_TOOLS_COUNT" ] || AGY_TOOLS_COUNT=0
    if [ "$AGY_TOOLS_COUNT" -eq 1 ]; then
        AGY_TOOLS_ROOT="$(head -n 1 "$AGY_TOOLS_MATCHES")"
        if ! agy_tools_write_marker "$AGY_TOOLS_ROOT"; then
            rm -f "$AGY_TOOLS_MATCHES"
            agy_tools_fail "found the root but could not write the root marker: $AGY_TOOLS_MARKER"
            exit 1
        fi
        printf '%s\n' "[agy-tools] repaired root marker, root is now: $AGY_TOOLS_ROOT" >&2
    elif [ "$AGY_TOOLS_COUNT" -gt 1 ]; then
        agy_tools_fail "$AGY_TOOLS_COUNT candidate agy-tools roots found; refusing to adopt any of them."
        while IFS= read -r agy_candidate; do
            [ -n "$agy_candidate" ] || continue
            printf '%s\n' "[agy-tools]   candidate: $agy_candidate" >&2
        done < "$AGY_TOOLS_MATCHES"
        printf '%s\n' "[agy-tools] ERROR: root marker left untouched: $AGY_TOOLS_MARKER" >&2
        agy_tools_reinstall_hint
        rm -f "$AGY_TOOLS_MATCHES"
        exit 1
    fi
    rm -f "$AGY_TOOLS_MATCHES"
fi

if ! agy_tools_identity_ok "$AGY_TOOLS_ROOT"; then
    agy_tools_fail "the agy-tools repository root could not be found."
    printf '%s\n' "[agy-tools]   marker : $AGY_TOOLS_MARKER" >&2
    printf '%s\n' "[agy-tools]   scanned: $HOME for bin/$AGY_TOOLS_SCRIPT (depth $AGY_TOOLS_SCAN_DEPTH, symlinks skipped)" >&2
    agy_tools_reinstall_hint
    exit 1
fi

exec node "$AGY_TOOLS_ROOT/bin/$AGY_TOOLS_SCRIPT" "$@"
AGY_TOOLS_WRAPPER
    chmod +x "$_dest" 2>/dev/null || true
}

echo "[INFO] Linking agy-tools globally via npm link..."
cd "$ROOT_DIR"

if npm link >/dev/null 2>&1; then
    echo ""
    echo "[SUCCESS] agy-tools, agy-tokens, agy-dashboard, and antigravity-tools installed globally!"
    if ! write_root_marker "$ROOT_DIR"; then
        echo "[ERROR] Could not write the root marker: $ROOT_MARKER" >&2
        echo "[ERROR] Fix the error above, then re-run: bash scripts/install.sh" >&2
        exit 1
    fi
else
    echo ""
    echo "[WARN] Global npm link required sudo or failed. Installing self-healing wrappers..."
    USER_BIN="$HOME/.local/bin"
    mkdir -p "$USER_BIN"
    # The marker goes in first and is FATAL: a wrapper that exists without a
    # marker would rescan the whole profile on every single run, so a marker
    # that cannot be written aborts the install instead of degrading.
    if ! write_root_marker "$ROOT_DIR"; then
        echo "[ERROR] Could not write the root marker: $ROOT_MARKER" >&2
        echo "[ERROR] Fix the error above, then re-run: bash scripts/install.sh" >&2
        exit 1
    fi
    write_wrapper "$USER_BIN/agy-tools" "agy-tools.js"
    write_wrapper "$USER_BIN/antigravity-tools" "agy-tools.js"
    write_wrapper "$USER_BIN/agy-tokens" "agy-tokens.js"
    write_wrapper "$USER_BIN/agy-dashboard" "agy-dashboard.js"
    echo "[SUCCESS] Created self-healing wrappers in $USER_BIN"
    echo "Make sure $USER_BIN is in your PATH."
    echo "The wrappers re-resolve the repository root at run time, so they survive moving this folder."
fi

echo ""
echo "[INFO] Deploying the Antigravity integrations with agy pro..."
echo "[INFO]   statusLine, rules, plugins, skills, lifecycle hooks"
# Trusted path first: agy-pro keeps its shim at the fixed user-owned path below
# (~/.agy-pro/bin, the same directory install.ps1 deploys to), so invoke THAT by
# absolute path. A PATH-earlier `agy` would otherwise run attacker code holding
# this deployment's --yes and could persist a payload in the statusLine slot
# (CWE-426 untrusted search path). The .exe twin is what Git Bash on Windows sees.
AGY_DOOR=""
for _agy_shim in "$HOME/.agy-pro/bin/agy" "$HOME/.agy-pro/bin/agy.exe"; do
    if [ -x "$_agy_shim" ]; then
        AGY_DOOR="$_agy_shim"
        break
    fi
done
# No agy-pro shim on this machine: fall back to the CLI that PATH resolves.
if [ -z "$AGY_DOOR" ] && command -v agy >/dev/null 2>&1; then
    AGY_DOOR="agy"
fi
if [ -n "$AGY_DOOR" ]; then
    if ! "$AGY_DOOR" pro integrations apply tools --yes; then
        echo "[ERROR] agy pro integrations apply tools failed; the statusLine integration and the rules/plugins/skills/hooks deployment were NOT completed." >&2
        echo "[ERROR] Fix the error above, then re-run: bash scripts/install.sh" >&2
        exit 1
    fi
else
    echo "[WARN] The agy CLI is not in your PATH, so the Antigravity integrations were NOT deployed."
    echo "[WARN] After agy is installed, run this exact command once:"
    echo "         agy pro integrations apply tools --yes"
    echo "[WARN] Then restart Antigravity CLI (agy) to start seeing real-time token tracking."
fi

echo "Try running:"
echo "  agy-tools --version"
echo "  agy-tools prices --currency krw"
echo "  agy-tokens --help"
echo ""
