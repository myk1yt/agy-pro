//go:build ignore

// Command gen generates ../tables.go from the Unicode Character Database
// data files EastAsianWidth.txt and DerivedGeneralCategory.txt, pinned to
// Unicode 15.1.0. The data files live next to this tool so the checked-in
// tables are reproducible offline.
//
// Usage (from this directory):
//
//	go run gen.go   (or: go run main.go after refreshing the .txt files)
//
// Table semantics emitted into ../tables.go:
//   - EastAsianWidth W or F            -> 2 cells
//   - General_Category Mn, Me, or Cf   -> 0 cells
//   - everything else (incl. A, H, N, Na) -> 1 cell
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

const unicodeVersion = "15.1.0"

type span struct{ lo, hi rune }

// parseUCD reads a UCD property file of the form "CODE ; PROP" or
// "FIRST..LAST ; PROP" and returns merged, sorted ranges for the given
// property values.
func parseUCD(path string, want map[string]bool) ([]span, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var spans []span
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1024*1024), 1024*1024)
	for sc.Scan() {
		line := sc.Text()
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		fields := strings.Split(line, ";")
		if len(fields) != 2 {
			continue
		}
		prop := strings.TrimSpace(fields[1])
		if !want[prop] {
			continue
		}
		var lo, hi rune
		cp := strings.TrimSpace(fields[0])
		if i := strings.Index(cp, ".."); i >= 0 {
			if _, err := fmt.Sscanf(cp[:i], "%X", &lo); err != nil {
				return nil, fmt.Errorf("%s: bad range %q: %w", path, cp, err)
			}
			if _, err := fmt.Sscanf(cp[i+2:], "%X", &hi); err != nil {
				return nil, fmt.Errorf("%s: bad range %q: %w", path, cp, err)
			}
		} else {
			if _, err := fmt.Sscanf(cp, "%X", &lo); err != nil {
				return nil, fmt.Errorf("%s: bad code point %q: %w", path, cp, err)
			}
			hi = lo
		}
		spans = append(spans, span{lo, hi})
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	return merge(spans), nil
}

func merge(in []span) []span {
	sort.Slice(in, func(i, j int) bool {
		if in[i].lo != in[j].lo {
			return in[i].lo < in[j].lo
		}
		return in[i].hi < in[j].hi
	})
	out := in[:0]
	for _, s := range in {
		if len(out) > 0 && s.lo <= out[len(out)-1].hi+1 {
			if s.hi > out[len(out)-1].hi {
				out[len(out)-1].hi = s.hi
			}
			continue
		}
		out = append(out, s)
	}
	return out
}

func emit(w *bufio.Writer, varName, source string, spans []span) {
	fmt.Fprintf(w, "// %s lists code points whose display width is not the default\n", varName)
	fmt.Fprintf(w, "// 1 cell. Source: %s (Unicode %s).\n", source, unicodeVersion)
	fmt.Fprintf(w, "var %s = [...][2]rune{\n", varName)
	for _, s := range spans {
		fmt.Fprintf(w, "\t{0x%X, 0x%X},\n", s.lo, s.hi)
	}
	fmt.Fprintf(w, "}\n\n")
}

func main() {
	wide, err := parseUCD("EastAsianWidth.txt", map[string]bool{"W": true, "F": true})
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	// EastAsianWidth.txt assigns W by default to the unassigned code points
	// of the CJK blocks below; those ranges are not listed as data lines.
	// Add them explicitly so the tables cover the full default-W blocks.
	wide = merge(append(wide,
		span{0x3400, 0x4DBF},   // CJK Unified Ideographs Extension A
		span{0x4E00, 0x9FFF},   // CJK Unified Ideographs
		span{0xF900, 0xFAFF},   // CJK Compatibility Ideographs
		span{0x20000, 0x2FFFD}, // Plane 2
		span{0x30000, 0x3FFFD}, // Plane 3
	))
	zero, err := parseUCD("DerivedGeneralCategory.txt", map[string]bool{"Mn": true, "Me": true, "Cf": true})
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	out, err := os.Create("../tables.go")
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	defer out.Close()

	var buf bytes.Buffer
	w := bufio.NewWriter(&buf)

	fmt.Fprintln(w, "// Code generated by gen; DO NOT EDIT.")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// Data sources (checked in next to the generator, both Unicode", unicodeVersion+"):")
	fmt.Fprintln(w, "//   - gen/EastAsianWidth.txt            (property W or F -> 2 cells)")
	fmt.Fprintln(w, "//   - gen/DerivedGeneralCategory.txt    (category Mn, Me, or Cf -> 0 cells)")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// Everything else, including EastAsianWidth A (Ambiguous), H, N, Na,")
	fmt.Fprintln(w, "// measures 1 cell (Ambiguous resolves narrow, per UAX #11 and observed")
	fmt.Fprintln(w, "// Windows terminal behavior).")
	fmt.Fprintln(w, "//")
	fmt.Fprintln(w, "// Regenerate after refreshing the data files:")
	fmt.Fprintln(w, "//   cd internal/cellwidth/gen && go run main.go")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "package cellwidth")
	fmt.Fprintln(w)
	emit(w, "wideRanges", "EastAsianWidth.txt properties W,F", wide)
	emit(w, "zeroRanges", "DerivedGeneralCategory.txt categories Mn,Me,Cf", zero)
	if err := w.Flush(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, "gofmt:", err)
		os.Exit(1)
	}
	if _, err := out.Write(formatted); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	fmt.Printf("wideRanges: %d spans, zeroRanges: %d spans (Unicode %s)\n", len(wide), len(zero), unicodeVersion)
}
